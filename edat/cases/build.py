"""Generate, validate and write the agentic case files.

    python -m edat.cases.build                       # every generator
    python -m edat.cases.build --module select --no-heldout --check-only

* The development split is generated from the public seed and written to
  `test_fixtures/agentic/dev/<family>/<lane>.<module>.yaml` (committed).
* The held-out split is generated from a private seed (kept in
  `$EDAT_PRIVATE_DIR/agentic/heldout_seed`, created on first use) and written
  to `$EDAT_PRIVATE_DIR/agentic/heldout/<family>/<lane>.<module>.yaml`. It is never
  written inside the repository.
* Every case is checked with `edat.cases.oracle.check_case` (the oracle passes
  on every checked world seed, the null model fails). A case that fails is
  reported and NOT written.
* Counts per family, lane and split go to `test_fixtures/agentic/counts.json`
  (the STATUS page reads them).
"""
from __future__ import annotations

import argparse
import json
import random
import secrets
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

from edat.cases.generators import modules
from edat.cases.loader import DEV_DIR, REPO, heldout_dir, private_dir
from edat.cases.oracle import check_case

PUBLIC_SEED = 20261118
COUNTS = REPO / "test_fixtures" / "agentic" / "counts.json"


def private_seed() -> int:
    p = private_dir()
    if p is None:
        raise SystemExit("set EDAT_PRIVATE_DIR to build the held-out split (or pass --no-heldout)")
    f = p / "agentic" / "heldout_seed"
    if not f.exists():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(str(secrets.randbits(48)))
    return int(f.read_text().strip())


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str)


def write_cases(root: Path, cases: list[dict], header: str, module: str) -> dict[tuple[str, str], int]:
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for c in cases:
        groups[(c["family"], c["lane"])].append(c)
    counts = {}
    for (fam, lane), cs in sorted(groups.items()):
        d = root / fam
        d.mkdir(parents=True, exist_ok=True)
        body = yaml.dump(cs, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)
        (d / f"{lane}.{module}.yaml").write_text(f"# {header}\n# family {fam}, lane {lane}, {len(cs)} cases\n" + body)
        counts[(fam, lane)] = len(cs)
    return counts


def build(names: list[str] | None, *, heldout: bool, check_only: bool, seeds=(1, 2, 3)) -> int:
    mods = modules()
    if names:
        mods = {k: v for k, v in mods.items() if k in names}
    failures = 0
    totals: Counter = Counter()
    for name, mod in sorted(mods.items()):
        for split in ("dev", "heldout") if heldout else ("dev",):
            seed = PUBLIC_SEED if split == "dev" else private_seed()
            cases = mod.generate(split, random.Random(f"{name}|{seed}"))
            good = []
            for c in cases:
                c.setdefault("split", split)
                res = check_case(c, seeds=seeds)
                if res.ok:
                    good.append(c)
                else:
                    failures += 1
                    print(f"FAIL [{name}/{split}] {res.case_id}: " + " | ".join(res.problems[:3]), file=sys.stderr)
            print(f"{name}/{split}: {len(good)}/{len(cases)} cases valid")
            if check_only:
                continue
            if split == "dev":
                counts = write_cases(DEV_DIR, good, "Generated by edat.cases.build from the public seed. Do not edit by hand.", name)
            else:
                hd = heldout_dir()
                counts = write_cases(hd, good, "PRIVATE held-out split. Never commit, never send to a hosted model.", name)
            for (fam, lane), n in counts.items():
                totals[(name, fam, lane, split)] += n
    if not check_only and totals:
        existing = json.loads(COUNTS.read_text()) if COUNTS.exists() else {}
        for name in {k[0] for k in totals}:
            existing.pop(name, None)
        for (name, fam, lane, split), n in totals.items():
            existing.setdefault(name, {}).setdefault(fam, {}).setdefault(lane, {})[split] = n
        COUNTS.write_text(json.dumps(existing, indent=2, sort_keys=True) + "\n")
    return 1 if failures else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate and validate agentic cases")
    ap.add_argument("--module", action="append", help="generator module name (repeatable)")
    ap.add_argument("--no-heldout", action="store_true")
    ap.add_argument("--check-only", action="store_true")
    ap.add_argument("--seeds", default="1,2,3")
    a = ap.parse_args(argv)
    return build(a.module, heldout=not a.no_heldout, check_only=a.check_only,
                 seeds=tuple(int(x) for x in a.seeds.split(",")))


if __name__ == "__main__":
    sys.exit(main())
