SPLIT_VERSION = "edat-quality-splits/1"
REPO_ROOT = Path(__file__).resolve().parents[2]
DEV_DIR = REPO_ROOT / "test_fixtures" / "quality" / "dev"
PUBLIC_DEV_BASE_SEED = 20270000

# Total cases per family and benchmark version; dev gets 25 %, held-out 75 % (spec 03 s1.4).
PLAN = {
    "source_per_cell": 12,          # 5 types x 4 tiers x 12 = 240
    "numeric_per_kind": 12,         # 5 kinds x 12 = 60
    "schema_total": 60,
    "noisy_total": 80,              # 20 per noise kind
}
DEV_SHARE = 0.25
NUMERIC_PLAN = [  # (kind, source type) cycles; half of the 60 on spreadsheets
    ("sum", "sheet"), ("comparison", "sheet"), ("count", "sheet"), ("count", "calendar"),
    ("date_arith", "calendar"), ("free_slots", "calendar"),
]
NUMERIC_KIND_SOURCES = {"sum": ["sheet"], "comparison": ["sheet"], "count": ["sheet", "calendar"],
                        "date_arith": ["calendar"], "free_slots": ["calendar"]}
NUMERIC_TIERS = ("S", "M", "L")


class PrivateDirMissing(RuntimeError):
    pass


def private_dir() -> Path:
    p = os.environ.get("EDAT_PRIVATE_DIR")
    if not p:
        raise PrivateDirMissing("EDAT_PRIVATE_DIR is not set; the held-out split lives only there")
    root = Path(p).expanduser().resolve()
    if root == REPO_ROOT or REPO_ROOT in root.parents:
        raise PrivateDirMissing("EDAT_PRIVATE_DIR must be outside the repository")
    return root / "quality"


def _counts(total: int, split: str) -> int:
    dev = round(total * DEV_SHARE)
    return dev if split == "dev" else total - dev


class SeedSource:
    """Dev: public, sequential seeds. Held-out: private random seeds, stored privately."""

    def __init__(self, split: str, *, seeds_file: Path | None = None):
        self.split = split
        self.i = 0
        self.used: list[int] = []
        if split == "dev":
            self.pool = None
        else:
            self.file = seeds_file
            data = json.loads(self.file.read_text()) if self.file and self.file.exists() else {}
            self.pool = data.get("seeds") or [secrets.randbelow(2 ** 31 - 1) + 10 ** 9 for _ in range(4000)]
            if self.file and not self.file.exists():
                self.file.parent.mkdir(parents=True, exist_ok=True)
                self.file.write_text(json.dumps({"seeds": self.pool, "generator": GENERATOR_VERSION}))

    def next(self) -> int:
        if self.pool is None:
            s = PUBLIC_DEV_BASE_SEED + self.i
        else:
            s = self.pool[self.i]
        self.i += 1
        self.used.append(s)
        return s


def build_split(split: str, *, seeds: SeedSource | None = None, avoid: set[str] | None = None) -> dict[str, list[dict]]:
    """All four case families for one split, deterministic for a seed source.

    `avoid` holds planted anchors of the other split (codes, amounts, URLs); a
    case that would reuse one is regenerated from the next seed.
    """
    if split not in ("dev", "heldout"):
        raise ValueError(split)
    seeds = seeds or SeedSource(split)
    avoid = avoid or set()

    def fresh(make):
        for _ in range(50):
            c = make(seeds.next())
            if not c or not (_anchor_values(c) & avoid):
                return c
        raise RuntimeError("could not avoid anchor collisions")
    out: dict[str, list[dict]] = {"source": [], "numeric": [], "schema": [], "noisy": []}
    n_cell = _counts(PLAN["source_per_cell"], split)
    for st in SOURCE_TYPES:
        for tier in TIERS:
            for k in range(n_cell):
                out["source"].append(fresh(lambda sd: make_source_case(st, tier, seed=sd, split=split,
                                                                       index=len(out["source"]))))
    n_kind = _counts(PLAN["numeric_per_kind"], split)
    for kind, sources in NUMERIC_KIND_SOURCES.items():
        made = 0
        tries = 0
        while made < n_kind and tries < n_kind * 20:
            st = sources[made % len(sources)]
            tier = NUMERIC_TIERS[made % len(NUMERIC_TIERS)]
            if kind == "comparison" and tier == "S":
                tier = "M"
            c = fresh(lambda sd: make_numeric_case(st, tier, kind, seed=sd, split=split, index=len(out["numeric"])))
            tries += 1
            if c:
                out["numeric"].append(c)
                made += 1
    n_schema = _counts(PLAN["schema_total"], split)
    for i in range(n_schema):
        out["schema"].append(fresh(lambda sd: make_schema_case(SCHEMA_KINDS[i % len(SCHEMA_KINDS)], seed=sd,
                                                               split=split, index=i)))
    out["noisy"] = build_noisy(out, split, _counts(PLAN["noisy_total"], split), seeds)
    return out


def build_noisy(fams: dict[str, list[dict]], split: str, total: int, seeds: SeedSource) -> list[dict]:
    """Noisy request variants of point and numeric tasks (spec 03 s7.8)."""
    parents = []
    for c in fams["source"]:
        for t in c["tasks"]:
            if t["kind"] == "point" and c["tier"] in ("S", "M"):
                parents.append((c, t))
    for c in fams["numeric"]:
        parents += [(c, t) for t in c["tasks"]]
    out = []
    per_kind = total // len(NOISE_KINDS)
    i = 0
    for kind in NOISE_KINDS:
        made = 0
        while made < per_kind and i < len(parents) * 4:
            c, t = parents[i % len(parents)]
            i += 1
            s = seeds.next()
            alts = (t.get("numeric") or {}).get("labels")
            noisy = make_noisy(t["request"], kind, s, **({"alternatives": alts} if kind == "self_correction" else {}))
            if not noisy or noisy == t["request"]:
                continue
            out.append({"schema": "edat.quality.noisy/1", "case_id": f"q.noisy.{kind}.{split}.{len(out):03d}",
                        "family": "noisy", "split": split, "seed": s, "noise_kind": kind,
                        "parent_case_id": c["case_id"], "parent_task_id": t["task_id"], "request": noisy,
                        "clean_request": t["request"], "scored_for": "correctness" if kind == "self_correction"
                        else "consistency"})
            made += 1
    return out


