"""Build, store and check EDAT's quality splits (spec 03 s1.4, s7, s8).

- The development split (25 % of each case family) is generated from public
  seeds and committed under test_fixtures/quality/dev/.
- The held-out split (75 %) is generated by the same code from private seeds.
  It lives only under $EDAT_PRIVATE_DIR/quality/ and is never committed.
- `overlap_report` checks the two splits share no seed, case id, planted
  anchor or source item; `overlap_with_rows` is the private n-gram check
  against a training-row file (only its counts are published).
- `validate_case` proves each case's planted facts are present in its source
  and that an empty answer scores zero on every task.

    python -m edat.quality.splits build-dev
    python -m edat.quality.splits build-heldout          # needs EDAT_PRIVATE_DIR
    python -m edat.quality.splits validate [--heldout]
    python -m edat.quality.splits overlap
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import secrets
import sys
from collections import Counter
from pathlib import Path

from edat.quality import normalize as N
from edat.quality.generate import (GENERATOR_VERSION, SOURCE_TYPES, TIERS, anchor_type, iter_tasks,
                                   make_numeric_case, make_source_case)
from edat.quality.noise import NOISE_KINDS, make_noisy
from edat.quality.render import render_sources
from edat.quality.schema_cases import SCHEMA_KINDS, make_schema_case

SPLIT_VERSION = "edat-quality-splits/1"
REPO_ROOT = Path(__file__).resolve().parents[2]
DEV_DIR = REPO_ROOT / "test_fixtures" / "quality" / "dev"
PUBLIC_DEV_BASE_SEED = 20270000

# Total cases per family and benchmark version; dev gets 25 %, held-out 75 % (spec 03 s1.4).
PLAN = {
    "source_per_cell": 12,          # 5 types x 4 tiers x 12 = 240
    "numeric_per_kind": 12,         # 5 kinds x 12 = 60
    "schema_total": 60,
    "noisy_total": 80,              # 20 per noise kind
}
DEV_SHARE = 0.25
NUMERIC_PLAN = [  # (kind, source type) cycles; half of the 60 on spreadsheets
    ("sum", "sheet"), ("comparison", "sheet"), ("count", "sheet"), ("count", "calendar"),
    ("date_arith", "calendar"), ("free_slots", "calendar"),
]
NUMERIC_KIND_SOURCES = {"sum": ["sheet"], "comparison": ["sheet"], "count": ["sheet", "calendar"],
                        "date_arith": ["calendar"], "free_slots": ["calendar"]}
NUMERIC_TIERS = ("S", "M", "L")


class PrivateDirMissing(RuntimeError):
    pass


def private_dir() -> Path:
    p = os.environ.get("EDAT_PRIVATE_DIR")
    if not p:
        raise PrivateDirMissing("EDAT_PRIVATE_DIR is not set; the held-out split lives only there")
    root = Path(p).expanduser().resolve()
    if root == REPO_ROOT or REPO_ROOT in root.parents:
        raise PrivateDirMissing("EDAT_PRIVATE_DIR must be outside the repository")
    return root / "quality"


def _counts(total: int, split: str) -> int:
    dev = round(total * DEV_SHARE)
    return dev if split == "dev" else total - dev


class SeedSource:
    """Dev: public, sequential seeds. Held-out: private random seeds, stored privately."""

    def __init__(self, split: str, *, seeds_file: Path | None = None):
        self.split = split
        self.i = 0
        self.used: list[int] = []
        if split == "dev":
            self.pool = None
        else:
            self.file = seeds_file
            data = json.loads(self.file.read_text()) if self.file and self.file.exists() else {}
            self.pool = data.get("seeds") or [secrets.randbelow(2 ** 31 - 1) + 10 ** 9 for _ in range(4000)]
            if self.file and not self.file.exists():
                self.file.parent.mkdir(parents=True, exist_ok=True)
                self.file.write_text(json.dumps({"seeds": self.pool, "generator": GENERATOR_VERSION}))

    def next(self) -> int:
        if self.pool is None:
            s = PUBLIC_DEV_BASE_SEED + self.i
        else:
            s = self.pool[self.i]
        self.i += 1
        self.used.append(s)
        return s


def build_split(split: str, *, seeds: SeedSource | None = None, avoid: set[str] | None = None) -> dict[str, list[dict]]:
    """All four case families for one split, deterministic for a seed source.

    `avoid` holds planted anchors of the other split (codes, amounts, URLs); a
    case that would reuse one is regenerated from the next seed.
    """
    if split not in ("dev", "heldout"):
        raise ValueError(split)
    seeds = seeds or SeedSource(split)
    avoid = avoid or set()

    def fresh(make):
        for _ in range(50):
            c = make(seeds.next())
            if not c or not (_anchor_values(c) & avoid):
                return c
        raise RuntimeError("could not avoid anchor collisions")
    out: dict[str, list[dict]] = {"source": [], "numeric": [], "schema": [], "noisy": []}
    n_cell = _counts(PLAN["source_per_cell"], split)
    for st in SOURCE_TYPES:
        for tier in TIERS:
            for k in range(n_cell):
                out["source"].append(fresh(lambda sd: make_source_case(st, tier, seed=sd, split=split,
                                                                       index=len(out["source"]))))
    n_kind = _counts(PLAN["numeric_per_kind"], split)
    for kind, sources in NUMERIC_KIND_SOURCES.items():
        made = 0
        tries = 0
        while made < n_kind and tries < n_kind * 20:
            st = sources[made % len(sources)]
            tier = NUMERIC_TIERS[made % len(NUMERIC_TIERS)]
            if kind == "comparison" and tier == "S":
                tier = "M"
            c = fresh(lambda sd: make_numeric_case(st, tier, kind, seed=sd, split=split, index=len(out["numeric"])))
            tries += 1
            if c:
                out["numeric"].append(c)
                made += 1
    n_schema = _counts(PLAN["schema_total"], split)
    for i in range(n_schema):
        out["schema"].append(fresh(lambda sd: make_schema_case(SCHEMA_KINDS[i % len(SCHEMA_KINDS)], seed=sd,
                                                               split=split, index=i)))
    out["noisy"] = build_noisy(out, split, _counts(PLAN["noisy_total"], split), seeds)
    return out


def build_noisy(fams: dict[str, list[dict]], split: str, total: int, seeds: SeedSource) -> list[dict]:
    """Noisy request variants of point and numeric tasks (spec 03 s7.8)."""
    parents = []
    for c in fams["source"]:
        for t in c["tasks"]:
            if t["kind"] == "point" and c["tier"] in ("S", "M"):
                parents.append((c, t))
    for c in fams["numeric"]:
        parents += [(c, t) for t in c["tasks"]]
    out = []
    per_kind = total // len(NOISE_KINDS)
    i = 0
    for kind in NOISE_KINDS:
        made = 0
        while made < per_kind and i < len(parents) * 4:
            c, t = parents[i % len(parents)]
            i += 1
            s = seeds.next()
            alts = (t.get("numeric") or {}).get("labels")
            noisy = make_noisy(t["request"], kind, s, **({"alternatives": alts} if kind == "self_correction" else {}))
            if not noisy or noisy == t["request"]:
                continue
            out.append({"schema": "edat.quality.noisy/1", "case_id": f"q.noisy.{kind}.{split}.{len(out):03d}",
                        "family": "noisy", "split": split, "seed": s, "noise_kind": kind,
                        "parent_case_id": c["case_id"], "parent_task_id": t["task_id"], "request": noisy,
                        "clean_request": t["request"], "scored_for": "correctness" if kind == "self_correction"
                        else "consistency"})
            made += 1
    return out


# --------------------------------------------------------------------------
# Storage
# --------------------------------------------------------------------------

def _dump(path: Path, rows: list[dict]) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = "".join(json.dumps(r, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n" for r in rows)
    path.write_text(data, encoding="utf-8")
    return hashlib.sha256(data.encode()).hexdigest()


def write_split(fams: dict[str, list[dict]], root: Path, split: str, seeds: SeedSource) -> dict:
    manifest = {"schema": "edat.quality.split-manifest/1", "split": split, "generator": GENERATOR_VERSION,
                "splits_version": SPLIT_VERSION, "files": {}, "counts": {}}
    for fam, rows in fams.items():
        manifest["files"][f"{fam}.jsonl"] = _dump(root / f"{fam}.jsonl", rows)
        manifest["counts"][fam] = len(rows)
    manifest["counts_by_source_type"] = dict(Counter(f"{c['source_type']}/{c['tier']}" for c in fams["source"]))
    manifest["counts_numeric_by_kind"] = dict(Counter(c["tasks"][0]["numeric"]["kind"] for c in fams["numeric"]))
    manifest["counts_schema_by_kind"] = dict(Counter(c["schema_kind"] for c in fams["schema"]))
    manifest["counts_noisy_by_kind"] = dict(Counter(c["noise_kind"] for c in fams["noisy"]))
    manifest["tasks"] = sum(len(c["tasks"]) for f in ("source", "numeric", "schema") for c in fams[f])
    if split == "dev":
        manifest["seeds"] = {"base": PUBLIC_DEV_BASE_SEED, "count": len(seeds.used)}
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return manifest


def load_split(root: Path) -> dict[str, list[dict]]:
    out = {}
    for fam in ("source", "numeric", "schema", "noisy"):
        p = root / f"{fam}.jsonl"
        out[fam] = [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()] if p.exists() else []
    return out


def load_dev() -> dict[str, list[dict]]:
    return load_split(DEV_DIR)


def load_heldout() -> dict[str, list[dict]]:
    return load_split(private_dir() / "heldout")


def all_cases(fams: dict[str, list[dict]]) -> list[dict]:
    return fams["source"] + fams["numeric"] + fams["schema"]


# --------------------------------------------------------------------------
# Overlap between splits, and against training rows
# --------------------------------------------------------------------------

def _anchor_values(c: dict) -> set[str]:
    vals = set()
    for f in c.get("facts", []):
        for k, v in f["anchors"].items():
            if anchor_type(k) in ("code", "amount", "url"):
                vals.add(f"{anchor_type(k)}:{v}")
    for t in c.get("traps", []):
        for k, v in t["anchors"].items():
            if anchor_type(k) in ("code", "url"):
                vals.add(f"{anchor_type(k)}:{v}")
    return vals


def _item_hashes(c: dict) -> set[str]:
    out = set()
    for it in c.get("items", []):
        body = json.dumps({k: v for k, v in it.items() if k not in ("id", "order")}, sort_keys=True)
        out.add(hashlib.sha256(body.encode()).hexdigest())
    return out


def _ngrams(text: str, n: int) -> set[tuple]:
    toks = re.findall(r"[a-z0-9]+", text.lower())
    return {tuple(toks[i:i + n]) for i in range(len(toks) - n + 1)}


def overlap_report(dev: dict[str, list[dict]], held: dict[str, list[dict]]) -> dict:
    """Dev and held-out must share no seed, case id, planted anchor or identical source item."""
    d_cases, h_cases = all_cases(dev), all_cases(held)
    d_seeds = {c["seed"] for c in d_cases} | {c["seed"] for c in dev["noisy"]}
    h_seeds = {c["seed"] for c in h_cases} | {c["seed"] for c in held["noisy"]}
    d_ids = {c["case_id"] for c in d_cases + dev["noisy"]}
    h_ids = {c["case_id"] for c in h_cases + held["noisy"]}
    d_anchor = set().union(*[_anchor_values(c) for c in d_cases]) if d_cases else set()
    h_anchor = set().union(*[_anchor_values(c) for c in h_cases]) if h_cases else set()
    d_items = set().union(*[_item_hashes(c) for c in d_cases]) if d_cases else set()
    h_items = set().union(*[_item_hashes(c) for c in h_cases]) if h_cases else set()
    d_fact_txt = {f["text"] for c in d_cases for f in c.get("facts", []) if f.get("text")}
    h_fact_txt = {f["text"] for c in h_cases for f in c.get("facts", []) if f.get("text")}
    rep = {
        "seeds_shared": len(d_seeds & h_seeds), "case_ids_shared": len(d_ids & h_ids),
        "planted_anchors_shared": sorted(d_anchor & h_anchor)[:20], "planted_anchors_shared_n": len(d_anchor & h_anchor),
        "source_items_shared": len(d_items & h_items), "planted_sentences_shared": len(d_fact_txt & h_fact_txt),
        "dev_cases": len(d_cases), "heldout_cases": len(h_cases),
    }
    rep["ok"] = not (rep["seeds_shared"] or rep["case_ids_shared"] or rep["source_items_shared"]
                     or rep["planted_sentences_shared"] or rep["planted_anchors_shared_n"])
    return rep


def overlap_with_rows(cases: list[dict], rows: list[str], *, n: int = 13, threshold: float = 0.05) -> dict:
    """Private T4 check: share of each case's rendered n-grams found in training rows.

    Returns counts only (publishable); per-case matches stay with the caller.
    """
    row_grams: set[tuple] = set()
    for r in rows:
        row_grams |= _ngrams(r, n)
    over = 0
    total_hits = 0
    for c in cases:
        txt = render_sources(c) + " " + " ".join(t["request"] for t in c["tasks"])
        g = _ngrams(txt, n)
        hits = len(g & row_grams)
        total_hits += hits
        if g and hits / len(g) > threshold:
            over += 1
    return {"cases": len(cases), "ngram_n": n, "threshold": threshold, "matching_ngrams": total_hits,
            "cases_above_threshold": over, "share_above_threshold": (over / len(cases)) if cases else 0.0}


# --------------------------------------------------------------------------
# Case validator
# --------------------------------------------------------------------------

_ALLOWED_DOMAIN = re.compile(r"^(?:[\w-]+\.)*(?:example\.(?:com|org|net)|[\w-]+\.(?:example|invalid|test))$")


def _anchor_in_source(text: str, atype: str, value, fact: dict | None, year: int) -> bool:
    if N.anchor_present(text, atype, value, case_year=year):
        return True
    if atype == "date":
        import datetime as dt
        d = dt.date.fromisoformat(str(value))
        if fact and fact.get("relative"):
            return True        # "next Friday": resolved by the generator, not written in the source
        if re.search(rf"\b{d.day}(st|nd|rd|th)\b", text):
            return True        # "moved to the 21st" in a thread whose messages carry the month
        compact = d.isoformat().replace("-", "")
        return compact in text  # .ics DTSTART
    if atype == "time":
        compact = str(value).replace(":", "")
        return re.search(rf"T{compact}00", text) is not None
    return False


def validate_case(case: dict) -> list[str]:
    """Return a list of problems; empty means the case is valid."""
    from edat.quality.scorers import empty_answer_scores_zero, score_task
    from edat.quality.jsonschema_lite import validate as js_validate
    errs: list[str] = []
    yr = case.get("case_year")
    for rendering in case.get("renderings", ["primary"]):
        src = render_sources(case, rendering)
        for f in case.get("facts", []):
            for k, v in f["anchors"].items():
                if not _anchor_in_source(src, anchor_type(k), v, f, yr):
                    errs.append(f"{rendering}: fact {f['fact_id']} anchor {k}={v!r} not in the source")
        for t in case.get("traps", []):
            if t["trap_type"] == "relative_date":
                continue   # the resolved date is the generator's answer, not text in the source
            for k, v in t["anchors"].items():
                if not _anchor_in_source(src, anchor_type(k), v, None, yr):
                    errs.append(f"{rendering}: trap {t['trap_id']} anchor {k}={v!r} not in the source")
    src = render_sources(case)
    ids = set()
    for t in iter_tasks(case):
        if t["task_id"] in ids:
            errs.append(f"duplicate task id {t['task_id']}")
        ids.add(t["task_id"])
        if not empty_answer_scores_zero(case, t):
            errs.append(f"{t['task_id']}: an empty answer does not score zero")
        if t["kind"] == "extraction":
            problems = js_validate(t["gold"], t["schema"])
            if problems:
                errs.append(f"{t['task_id']}: gold does not validate: {problems[0].message}")
            ref = json.dumps(t["gold"])
        else:
            ref = t.get("reference_answer") or ""
        if ref:
            m = score_task(ref, case, t, source_text=src)
            if not m["pass"]:
                errs.append(f"{t['task_id']}: the reference answer does not pass")
    blob = json.dumps(case, ensure_ascii=False)
    for m in re.finditer(r"[\w.+-]+@([\w-]+(?:\.[\w-]+)+)", blob):
        if not _ALLOWED_DOMAIN.match(m.group(1).lower()):
            errs.append(f"email outside .example/.invalid: {m.group(0)}")
    for m in re.finditer(r"https?://([^/\s\"']+)", blob):
        if not _ALLOWED_DOMAIN.match(m.group(1).lower().split(":")[0]):
            errs.append(f"URL outside .example/.invalid: {m.group(0)}")
    if re.search(r"/(Users|home)/[A-Za-z]", blob):
        errs.append("absolute local path in case")
    return errs


def validate_split(fams: dict[str, list[dict]]) -> dict:
    problems = {}
    for c in all_cases(fams):
        e = validate_case(c)
        if e:
            problems[c["case_id"]] = e
    parents = {c["case_id"] for c in all_cases(fams)}
    for n in fams.get("noisy", []):
        if n["parent_case_id"] not in parents:
            problems[n["case_id"]] = ["parent case missing"]
    return {"cases": len(all_cases(fams)), "noisy": len(fams.get("noisy", [])), "invalid": len(problems),
            "problems": problems}


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m edat.quality.splits", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build-dev", help="generate the public development split into test_fixtures/quality/dev")
    sub.add_parser("build-heldout", help="generate the private held-out split into $EDAT_PRIVATE_DIR/quality")
    v = sub.add_parser("validate", help="validate every case in a split")
    v.add_argument("--heldout", action="store_true")
    sub.add_parser("overlap", help="check the dev and held-out splits share nothing (needs EDAT_PRIVATE_DIR)")
    a = ap.parse_args(argv)
    if a.cmd == "build-dev":
        seeds = SeedSource("dev")
        fams = build_split("dev", seeds=seeds)
        print(json.dumps(write_split(fams, DEV_DIR, "dev", seeds)["counts"]))
    elif a.cmd == "build-heldout":
        root = private_dir()
        seeds = SeedSource("heldout", seeds_file=root / "heldout-seeds.json")
        dev = load_dev()
        avoid = set().union(*[_anchor_values(c) for c in all_cases(dev)]) if all_cases(dev) else set()
        fams = build_split("heldout", seeds=seeds, avoid=avoid)
        print(json.dumps(write_split(fams, root / "heldout", "heldout", seeds)["counts"]))
    elif a.cmd == "validate":
        fams = load_heldout() if a.heldout else load_dev()
        rep = validate_split(fams)
        print(json.dumps({k: v for k, v in rep.items() if k != "problems"}))
        for cid, e in list(rep["problems"].items())[:20]:
            print(cid, e[:3])
        return 1 if rep["invalid"] else 0
    elif a.cmd == "overlap":
        rep = overlap_report(load_dev(), load_heldout())
        print(json.dumps(rep))
        return 0 if rep["ok"] else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
