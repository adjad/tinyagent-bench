"""Build the screen case splits from the family generators (spec 11 §3.11, S5).

    python -m edat.screen.cases.build --no-heldout          # development split only
    EDAT_PRIVATE_DIR=<private folder> python -m edat.screen.cases.build

For each family and split: generate the cases with a fixed seed, validate
them, run the oracle check on world seeds 1-3 (which also sets `optimal` and
`max_steps`), run the authoring lint, pick the core subset (stratified by
level, by Guard sub-family, injection pairs kept together) and the
screenshot-track cases, then write

* the development split to `test_fixtures/screen/dev/<family>.yaml` with
  `test_fixtures/screen/counts.json`;
* the held-out split to `$EDAT_PRIVATE_DIR/screen/heldout/<family>.yaml`. Its
  seed is read from `$EDAT_PRIVATE_DIR/screen/heldout-seed.txt` (created on
  first use, never committed). Held-out cases are never written inside the
  repository and never sent to a hosted model.

A case that fails a check stops the build with its problems listed.
"""
from __future__ import annotations

import argparse
import importlib
import json
import os
import random
import secrets
import sys
from collections import Counter, defaultdict
from pathlib import Path

from edat.screen.author import common
from edat.screen.cases.lint import lint_case
from edat.screen.cases.oracle import check_case
from edat.screen.cases.schema import validate_case
from edat.screen.cases.store import save_cases

DEV_SEED = 1101
REPO = Path(__file__).resolve().parents[3]
DEV_DIR = REPO / "test_fixtures" / "screen" / "dev"
COUNTS_FILE = REPO / "test_fixtures" / "screen" / "counts.json"
FAMILY_ORDER = ("ground", "read", "form", "flow", "disrupt", "cross", "guard")
ALL_FAMILIES = FAMILY_ORDER + ("pixel",)
HEADER = ("# Generated by edat/screen/cases/build.py from edat/screen/author/{family}.py. Do not edit by hand.\n"
          "# Public development split of EDAT spec 11 (on-screen app control). Every value is invented;\n"
          "# {{slots}} are filled from the world seed at bind time.\n")


class BuildError(RuntimeError):
    pass


def private_dir() -> Path | None:
    d = os.environ.get("EDAT_PRIVATE_DIR")
    return Path(d).expanduser() if d else None


def heldout_seed(pdir: Path) -> int:
    f = pdir / "screen" / "heldout-seed.txt"
    if f.exists():
        return int(f.read_text().strip())
    f.parent.mkdir(parents=True, exist_ok=True)
    seed = secrets.randbelow(2 ** 31)
    f.write_text(f"{seed}\n")
    return seed


def family_cases(family: str, split: str, seed: int) -> list[dict]:
    mod = importlib.import_module(f"edat.screen.author.{family}")
    n = common.PIXEL_SPLIT if family == "pixel" else common.counts(split)[family]
    rng = random.Random(f"screen:{family}:{split}:{seed}")
    cases = mod.generate(split, rng, n)
    if len(cases) != n:
        raise BuildError(f"{family}/{split}: generator returned {len(cases)} cases, wanted {n}")
    return cases


def check_all(cases: list[dict], *, lint: bool = True) -> list[str]:
    problems: list[str] = []
    ids = Counter(c["id"] for c in cases)
    problems += [f"duplicate id {i}" for i, k in ids.items() if k > 1]
    for c in cases:
        for p in validate_case(c):
            problems.append(f"{c.get('id')}: {p}")
    if problems:
        return problems
    for c in cases:
        r = check_case(c, set_budget=True)
        problems += [f"{c['id']}: {p}" for p in r.problems]
        if lint and r.ok:
            lr = lint_case(c)
            problems += [f"{c['id']}: lint: {p}" for p in lr.problems]
    return problems


def _strata(c: dict) -> tuple:
    return (c["family"], c.get("guard_kind") or "", c["level"])


def select_core(cases: list[dict], family: str, split: str, rng: random.Random) -> None:
    want = (common.DEV_CORE if split == "dev" else common.HELDOUT_CORE)[family]
    for c in cases:
        c["core"] = False
    if family == "guard":
        quota = common.GUARD_DEV_CORE if split == "dev" else common.GUARD_HELDOUT_CORE
        for kind, k in quota.items():
            pool = [c for c in cases if c.get("guard_kind") == kind and not c.get("twin_of")]
            rng.shuffle(pool)
            take = pool[: (k // 2 if kind == "injection" else k)]
            for c in take:
                c["core"] = True
                if kind == "injection":
                    for t in cases:
                        if t.get("twin_of") == c["id"]:
                            t["core"] = True
        return
    by_level = defaultdict(list)
    for c in cases:
        by_level[c["level"]].append(c)
    levels = sorted(by_level)
    targets = common.spread(want, levels, [len(by_level[lv]) for lv in levels])
    for lv in levels:
        pool = sorted(by_level[lv], key=lambda c: c["id"])
        rng.shuffle(pool)
        for c in pool[: targets.count(lv)]:
            c["core"] = True


def assign_tracks(all_cases: list[dict], rng: random.Random) -> None:
    """Screenshot track on 300 cases (the core's stratified 100 among them), both-track on 100."""
    for c in all_cases:
        c["tracks"] = ["ax_text"]
    core = sorted((c for c in all_cases if c.get("core")), key=lambda c: c["id"])
    rest = sorted((c for c in all_cases if not c.get("core")), key=lambda c: c["id"])

    def stratified(pool: list[dict], k: int) -> list[dict]:
        groups = defaultdict(list)
        for c in pool:
            groups[_strata(c)].append(c)
        keys = sorted(groups)
        for g in keys:
            rng.shuffle(groups[g])
        out: list[dict] = []
        i = 0
        while len(out) < k and any(groups[g] for g in keys):
            g = keys[i % len(keys)]
            if groups[g]:
                out.append(groups[g].pop())
            i += 1
        return out

    shot = stratified(core, (len(core) + 1) // 2)        # the core's stratified half (100 of 200)
    shot += stratified(rest, common.SCREENSHOT_FULL * len(all_cases) // 650 - len(shot))
    for c in shot:
        c["tracks"] = ["ax_text", "screenshot_som"]
    both = stratified([c for c in shot], common.BOTH_FULL * len(all_cases) // 650)
    for c in both:
        c["tracks"].append("ax_plus_screenshot")


def build(*, heldout: bool = True, families: tuple[str, ...] = ALL_FAMILIES, lint: bool = True,
          write: bool = True, out_dev: Path = DEV_DIR) -> dict:
    splits = [("dev", DEV_SEED)]
    pdir = private_dir()
    if heldout:
        if pdir is None:
            raise BuildError("set EDAT_PRIVATE_DIR to build the held-out split (or pass --no-heldout)")
        splits.append(("heldout", heldout_seed(pdir)))
    summary: dict = {"schema": "edat-screen-counts/v1", "splits": {}}
    for split, seed in splits:
        all_cases: list[dict] = []
        per_family: dict[str, list[dict]] = {}
        problems: list[str] = []
        for fam in families:
            cases = family_cases(fam, split, seed)
            for c in cases:
                c["split"] = split
            problems += check_all(cases, lint=lint)
            if fam != "pixel":       # family P is a diagnostic outside the 650 and the core
                select_core(cases, fam, split, random.Random(f"core:{fam}:{split}:{seed}"))
            per_family[fam] = cases
            all_cases += cases
        if problems:
            raise BuildError(f"{split}: {len(problems)} problems:\n" + "\n".join(problems[:200]))
        if set(FAMILY_ORDER) <= set(families):
            assign_tracks([c for c in all_cases if c["family"] != "pixel"], random.Random(f"tracks:{split}:{seed}"))
        if write:
            target = out_dev if split == "dev" else pdir / "screen" / "heldout"
            for fam, cases in per_family.items():
                save_cases(target / f"{fam}.yaml", cases, HEADER.format(family=fam))
        summary["splits"][split] = _count(all_cases)
    if write and "dev" in summary["splits"] and set(FAMILY_ORDER) <= set(families):
        COUNTS_FILE.parent.mkdir(parents=True, exist_ok=True)
        prev = json.loads(COUNTS_FILE.read_text()) if COUNTS_FILE.exists() else {}
        if "heldout" not in summary["splits"] and "heldout" in prev.get("splits", {}):
            summary["splits"]["heldout"] = prev["splits"]["heldout"]
        COUNTS_FILE.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    return summary


def _count(cases: list[dict]) -> dict:
    by = defaultdict(lambda: defaultdict(int))
    for c in cases:
        by[c["family"]][f"L{c['level']}"] += 1
        by[c["family"]]["total"] += 1
        if c.get("core"):
            by[c["family"]]["core"] += 1
        if c.get("guard_kind"):
            by[c["family"]][f"kind_{c['guard_kind']}"] += 1
        for t in c.get("tracks") or []:
            by["_tracks"][t] += 1
    out = {f: dict(v) for f, v in by.items()}
    out["_total"] = sum(1 for c in cases if c["family"] != "pixel")     # the 650-case set; P is counted apart
    out["_core"] = sum(1 for c in cases if c.get("core"))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--no-heldout", action="store_true")
    ap.add_argument("--family", action="append", help="limit to these families (no counts file update)")
    ap.add_argument("--no-lint", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="check only, write nothing")
    a = ap.parse_args(argv)
    fams = tuple(a.family) if a.family else ALL_FAMILIES
    try:
        s = build(heldout=not a.no_heldout, families=fams, lint=not a.no_lint, write=not a.dry_run)
    except BuildError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print(json.dumps(s, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
